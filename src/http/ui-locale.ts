/** Installs translation, persistence, cross-tab synchronization, and the language-setting controls. */
export const localeScript = String.raw`
    (() => {
      const bootstrap = window.__yourcharLocaleBootstrap || {};
      const key = bootstrap.key || "${UI_LOCALE_STORAGE_KEY}";
      const valid = bootstrap.valid || (value => ["system", "zh-CN", "en"].includes(value) ? value : "system");
      const systemLocale = bootstrap.systemLocale || (() => /^zh(?:-|$)/i.test(String(navigator.language || "en")) ? "zh-CN" : "en");
      const messages = ${encodedMessages};
      const phrases = ${encodedPhrases}.slice().sort((left, right) => right[0].length - left[0].length);
      const patterns = ${encodedPatterns}.map(([pattern, replacement]) => [new RegExp(pattern, "u"), replacement]);
      const translatedTextNodes = new Set();
      const translatedAttributes = new Set();
      const textRecords = new WeakMap();
      const attributeRecords = new WeakMap();
      const ignoredContentSelector = [
        "script", "style", "pre", "code", "textarea", "[contenteditable=true]",
        "#messages", "#historySearchResults", "#workspaceFilePreview", ".workspace-file-preview",
        "#conversationCharacter", "#conversationScene", "[data-i18n-user-content]",
        ".trace-block pre", ".message-content", ".bubble", ".creator-message > p",
        ".feature-test-reply .markdown-body", ".world-scene-text", ".diary-prose",
        "#characterProfileSoul", "#characterOwnedSkillMarkdown"
      ].join(",");
      let preference = valid(bootstrap.preference);
      let locale = preference === "system" ? systemLocale() : preference;
      let observer;
      let applying = false;

      function containsHan(value) { return /[\u3400-\u9fff]/u.test(value); }
      function english(source) {
        if (Object.prototype.hasOwnProperty.call(messages, source)) return messages[source];
        for (const [pattern, replacement] of patterns) if (pattern.test(source)) return source.replace(pattern, replacement);
        let result = source;
        for (const [from, to] of phrases) result = result.split(from).join(to);
        if (result !== source && !containsHan(result)) return result.replace(/\s+/g, " ").trim();
        return source;
      }
      function translateSource(source, targetLocale = locale) {
        return targetLocale === "en" ? english(source) : source;
      }
      function splitWhitespace(value) {
        const match = /^(\s*)([\s\S]*?)(\s*)$/u.exec(value);
        return { before: match?.[1] || "", core: match?.[2] || "", after: match?.[3] || "" };
      }
      function ignored(node) {
        const parent = node.nodeType === Node.ELEMENT_NODE ? node : node.parentElement;
        return Boolean(parent?.closest(ignoredContentSelector));
      }
      function userAuthored(source) {
        if (typeof state !== "object" || !state || !source) return false;
        const collections = [
          state.characters, state.worlds, state.worldConversations, state.groupChats, state.sessions,
          state.archivedSessions, state.scheduleItems, state.memories, state.managedMemories,
          state.workspaceFiles, state.peopleProfiles, state.modelProfiles, state.meetingPresets,
          state.characterOwnedSkills, state.characterSkillPackages
        ];
        const fields = new Set(["name", "title", "displayName", "text", "content", "description", "summary", "objective", "notes", "markdown", "soulMarkdown", "fileName", "path"]);
        const seen = new Set();
        const inspect = (value, depth = 0) => {
          if (depth > 3 || value === null || value === undefined) return false;
          if (typeof value === "string") return value.trim() === source;
          if (typeof value !== "object" || seen.has(value)) return false;
          seen.add(value);
          if (Array.isArray(value)) return value.some(entry => inspect(entry, depth + 1));
          return Object.entries(value).some(([field, entry]) => fields.has(field) && inspect(entry, depth + 1));
        };
        return collections.some(collection => inspect(collection));
      }
      function translateTextNode(node, register = false) {
        if (!node || node.nodeType !== Node.TEXT_NODE || ignored(node)) return;
        const current = node.nodeValue || "";
        let record = textRecords.get(node);
        if (!record) {
          const parts = splitWhitespace(current);
          if (!parts.core) return;
          if (!register && (english(parts.core) === parts.core || userAuthored(parts.core))) return;
          record = { source: parts.core, before: parts.before, after: parts.after, rendered: current };
          textRecords.set(node, record); translatedTextNodes.add(node);
        } else if (current !== record.rendered) {
          const parts = splitWhitespace(current);
          if (userAuthored(parts.core)) {
            textRecords.delete(node); translatedTextNodes.delete(node); return;
          }
          record.source = parts.core; record.before = parts.before; record.after = parts.after;
        }
        const rendered = record.before + translateSource(record.source) + record.after;
        record.rendered = rendered;
        if (node.nodeValue !== rendered) node.nodeValue = rendered;
      }
      function translateAttribute(element, name, register = false) {
        if (ignored(element) || !element.hasAttribute(name)) return;
        let records = attributeRecords.get(element);
        if (!records) { records = new Map(); attributeRecords.set(element, records); }
        const current = element.getAttribute(name) || "";
        let record = records.get(name);
        if (!record) {
          if (!current || (!register && english(current) === current)) return;
          record = { source: current, rendered: current }; records.set(name, record);
          translatedAttributes.add(element);
        } else if (current !== record.rendered) {
          record.source = current;
        }
        const rendered = translateSource(record.source);
        record.rendered = rendered;
        if (current !== rendered) element.setAttribute(name, rendered);
      }
      function translateTree(root, register = false) {
        if (!root || ignored(root)) return;
        if (root.nodeType === Node.TEXT_NODE) { translateTextNode(root, register); return; }
        if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return;
        const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
        let node;
        while ((node = walker.nextNode())) translateTextNode(node, register);
        const elements = root.nodeType === Node.ELEMENT_NODE ? [root, ...root.querySelectorAll("*")] : [...root.querySelectorAll("*")];
        for (const element of elements) for (const name of ["aria-label", "placeholder", "title"]) translateAttribute(element, name, register);
      }
      function renderRegistered() {
        applying = true;
        try {
          for (const node of [...translatedTextNodes]) {
            if (!node.isConnected) { translatedTextNodes.delete(node); continue; }
            translateTextNode(node);
          }
          for (const element of [...translatedAttributes]) {
            if (!element.isConnected) { translatedAttributes.delete(element); continue; }
            for (const name of ["aria-label", "placeholder", "title"]) translateAttribute(element, name);
          }
        } finally { applying = false; }
      }
      function updateControls() {
        document.querySelectorAll("[data-locale-choice]").forEach(button => {
          button.setAttribute("aria-pressed", String(button.dataset.localeChoice === preference));
        });
        const status = document.getElementById("localeStatus");
        if (!status) return;
        const current = locale === "zh-CN" ? "简体中文" : "English";
        status.textContent = locale === "en"
          ? (preference === "system" ? "Following system · currently " : "Currently ") + current + ". This choice is saved in this browser."
          : (preference === "system" ? "跟随系统 · 当前为" : "当前为") + current + "，选择会保存在此浏览器。";
      }
      function apply(value, persist = false) {
        preference = valid(value);
        locale = preference === "system" ? systemLocale() : preference;
        document.documentElement.lang = locale;
        document.documentElement.dataset.locale = locale;
        document.documentElement.dataset.localePreference = preference;
        if (persist) { try { localStorage.setItem(key, preference); } catch {} }
        renderRegistered();
        updateControls();
        delete document.documentElement.dataset.localePending;
        window.dispatchEvent(new CustomEvent("yourchar:localechange", { detail: { preference, locale } }));
      }

      window.yourcharLocale = {
        get preference() { return preference; },
        get locale() { return locale; },
        apply,
        t: (source) => translateSource(String(source)),
        translateTree: (root) => translateTree(root, false),
      };
      translateTree(document.body, true);
      observer = new MutationObserver(records => {
        if (applying) return;
        applying = true;
        try {
          for (const mutation of records) {
            if (mutation.type === "characterData") translateTextNode(mutation.target, false);
            if (mutation.type === "attributes") translateAttribute(mutation.target, mutation.attributeName, false);
            for (const node of mutation.addedNodes || []) translateTree(node, false);
          }
        } finally { applying = false; }
      });
      observer.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ["aria-label", "placeholder", "title"] });
      document.getElementById("localeChoices")?.addEventListener("click", event => {
        const button = event.target.closest("[data-locale-choice]");
        if (button) apply(button.dataset.localeChoice, true);
      });
      window.addEventListener("languagechange", () => { if (preference === "system") apply("system"); });
      window.addEventListener("storage", event => { if (event.key === key || event.key === null) apply(valid(event.newValue)); });
      updateControls();
      delete document.documentElement.dataset.localePending;
    })();
`;

function escapeInlineJson(value: string): string {
  return value.replaceAll("<", "\\u003c").replaceAll(">", "\\u003e").replaceAll("&", "\\u0026");
}
